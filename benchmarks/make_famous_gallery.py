"""docs/FAMOUS_DATASETS.md from results/famous/top10.json + results/famous/labels.json (no hand-typed numbers)."""
import json
from pathlib import Path

T = json.loads(Path('results/famous/top10.json').read_text())
LAB = json.loads(Path('results/famous/labels.json').read_text())
ORDER = ['diamonds', 'titanic', 'planets', 'taxis', 'california_housing', 'penguins', 'tips', 'iris_uci']
SRC = {'diamonds': 'seaborn-data `diamonds` (ggplot2)', 'titanic': 'seaborn-data `titanic`', 'planets': 'seaborn-data `planets` (NASA Exoplanet Archive extract)',
       'taxis': 'seaborn-data `taxis` (NYC TLC, March 2019)', 'california_housing': 'scikit-learn `fetch_california_housing`',
       'penguins': 'seaborn-data `penguins` (Palmer Station LTER)', 'tips': 'seaborn-data `tips`', 'iris_uci': 'UCI `iris.data` (original file)'}
fmt = lambda v: f"{v:.6g}" if isinstance(v, float) else str(v)
L = ['# TabLint on familiar datasets', '',
     'Exploratory scan with its protocol fixed before inference (preserved in Git history). TabLint (TabPFN-3.5, default '
     'threshold 2) was run on 8 well-known tables. For each table, **all top-10 flags are listed in rank order**. A flag is '
     'called a *verified error* only with a cited source or a physical or definitional argument; everything else is '
     '*plausible but unusual* (shown to be real) or *unverified*. Generated by `benchmarks/make_famous_gallery.py`.', '']
tot = {'verified error': 0, 'plausible but unusual': 0, 'unverified': 0}
rows = []
for name in ORDER:
    d = T[name]; lab = LAB.get(name, {})
    c = {'verified error': 0, 'plausible but unusual': 0, 'unverified': 0}
    for t in d['top10']:
        c[lab.get(str(t['rank']), {}).get('label', 'unverified')] += 1
    for k in c: tot[k] += c[k]
    rows.append(f"| {name} | {d['n_full']:,} | {d['n_scanned']:,} | {c['verified error']} | {c['plausible but unusual']} | {c['unverified']} |")
L += ['## Summary', '', '| Dataset | Rows | Scanned | Verified errors (top 10) | Plausible but unusual | Unverified |', '|---|---:|---:|---:|---:|---:|'] + rows
L += ['', f"Totals over {len(ORDER)} datasets: **{tot['verified error']} verified errors**, {tot['plausible but unusual']} plausible but unusual, "
      f"{tot['unverified']} unverified (not checked or not checkable). The UCI Auto MPG Buick (demo set) is a further verified error.", '',
      '**Known-answer check (pre-specified, UCI Iris).** The two errors documented in UCI\'s `iris.names` were **not flagged**:']
for k, v in T['iris_uci']['known_answer'].items():
    L.append(f"- {k} = {v['value']}: surprise {v['surprise']} (threshold 2), {'rank ' + str(v['rank']) if v['rank'] else 'not listed'}")
L += ['', 'These are 0.1–0.5 cm slips that sit inside natural flower-to-flower variation, so nothing in the row contradicts '
      'them. TabLint catches values that are implausible given the rest of the row, not small plausible ones.', '']
for name in ORDER:
    d = T[name]; lab = LAB.get(name, {})
    pats = ', '.join(p['column'] for p in d['patterns']) or 'none'
    L += [f"## {name}", '', f"Source: {SRC[name]}. {d['n_full']:,} rows (scanned {d['n_scanned']:,}); {d['issues']} issues listed; "
          f"column-level placeholder patterns: {pats}; {d['seconds']} s.", '',
          '| # | Row | Column | Recorded | TabPFN-3.5 expects | Surprise | Label | Note |', '|---:|---:|---|---:|---:|---:|---|---|']
    for t in d['top10']:
        l = lab.get(str(t['rank']), {})
        note = l.get('note', '') + (f" ([source]({l['source']}))" if l.get('source', '').startswith('http') else '')
        if not note and t['auto_checks']:
            note = 'auto-check: ' + '; '.join(t['auto_checks'])
        L.append(f"| {t['rank']} | {t['orig_row']} | {t['column']} | {fmt(t['value'])} | {fmt(t['suggested'])} | {t['surprise']} | "
                 f"{l.get('label', 'unverified')} | {note} |")
    L.append('')
L += ['## Notes', '',
      '- Rows are 0-based positions in the source table. For tables with more than 10,000 rows, a fixed 10,000-row sample '
      '(seed 0) plus every row with an impossible zero was scanned, as pre-registered.',
      '- "Unverified" does not mean wrong or right. These are prompts a data owner would check.',
      '- Data are loaded by URL from their public sources and are not redistributed here.']
Path('docs/FAMOUS_DATASETS.md').write_text('\n'.join(L) + '\n'); print('wrote docs/FAMOUS_DATASETS.md', tot)
