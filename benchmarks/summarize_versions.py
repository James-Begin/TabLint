"""Analysis fixed in docs/VERSION_COMPARISON_PREREG.md -> results/version_compare/summary.json + docs/VERSION_COMPARISON.md"""
import json, sys
from collections import defaultdict
from pathlib import Path
import numpy as np
from scipy.stats import wilcoxon

D = Path(sys.argv[1] if len(sys.argv) > 1 else 'results/version_compare')
V = ['V2', 'V3', 'V3_5', 'V3_5_FAST']; NAME = {'V2': 'TabPFN v2', 'V3': 'TabPFN v3', 'V3_5': 'TabPFN-3.5', 'V3_5_FAST': 'TabPFN-3.5-Fast'}
by = defaultdict(list)
for p in sorted(D.glob('*_80*.json')):
    r = json.loads(p.read_text()); by[r['dataset']].append(r)
rows = []
for ds, rs in sorted(by.items()):
    m = {v: float(np.mean([r['versions'][v]['precision_at_k'] for r in rs])) for v in V}
    a = {v: float(np.mean([r['versions'][v]['auroc'] for r in rs])) for v in V}
    s = {v: float(np.mean([r['versions'][v]['seconds'] for r in rs])) for v in V}
    rows.append({'dataset': ds, 'seeds': len(rs), 'p_at_k': m, 'auroc': a, 'seconds': s})
rng = np.random.default_rng(0)


def test(other):
    d = np.array([r['p_at_k']['V3_5'] - r['p_at_k'][other] for r in rows])
    b = [rng.choice(d, len(d)).mean() for _ in range(10000)]
    p = float(wilcoxon(d, alternative='greater').pvalue) if np.any(d != 0) else 1.0
    return {'wins': int((d > 0).sum()), 'losses': int((d < 0).sum()), 'datasets': len(d), 'mean_diff': float(d.mean()),
            'ci95': [float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5))], 'wilcoxon_p_one_sided': p, 'supported': p < 0.025}


h9, h10 = test('V2'), test('V3')
fast = np.array([r['p_at_k']['V3_5_FAST'] - r['p_at_k']['V3_5'] for r in rows])
speed = np.array([r['seconds']['V3_5'] / r['seconds']['V3_5_FAST'] for r in rows])
mean = {v: float(np.mean([r['p_at_k'][v] for r in rows])) for v in V}
secs = {v: float(np.sum([r['seconds'][v] * r['seeds'] for r in rows])) for v in V}
out = {'h9_v35_vs_v2': h9, 'h10_v35_vs_v3': h10,
       'fast_vs_35': {'mean_diff_p_at_k': float(fast.mean()), 'datasets_fast_worse': int((fast < 0).sum()), 'median_speedup': float(np.median(speed))},
       'mean_p_at_k': mean, 'total_seconds': secs, 'per_dataset': rows, 'runs': sum(r['seeds'] for r in rows)}
(D / 'summary.json').write_text(json.dumps(out, indent=2))
v = lambda h: 'supported' if h['supported'] else 'not supported'
L = ['# TabPFN version comparison (pre-registered: `docs/VERSION_COMPARISON_PREREG.md`)', '',
     f"Proofread cell-error benchmark, fresh seeds 801–805, 14 datasets, {out['runs']} tables; same injection and scoring as H6. "
     'Generated by `benchmarks/summarize_versions.py`.', '',
     '| | TabPFN v2 | TabPFN v3 | TabPFN-3.5 | TabPFN-3.5-Fast |', '|---|---:|---:|---:|---:|',
     '| Mean precision@k (14 datasets) | ' + ' | '.join(f"{mean[x]:.3f}" for x in V) + ' |',
     '| Total GPU seconds (all tables) | ' + ' | '.join(f"{secs[x]:.0f}" for x in V) + ' |', '',
     f"- **H9, TabPFN-3.5 > v2:** wins {h9['wins']}, losses {h9['losses']} of {h9['datasets']}; mean {h9['mean_diff']:+.3f} "
     f"[{h9['ci95'][0]:+.3f}, {h9['ci95'][1]:+.3f}]; one-sided Wilcoxon p = {h9['wilcoxon_p_one_sided']:.2g}. {v(h9)} (alpha 0.025).",
     f"- **H10, TabPFN-3.5 > v3:** wins {h10['wins']}, losses {h10['losses']} of {h10['datasets']}; mean {h10['mean_diff']:+.3f} "
     f"[{h10['ci95'][0]:+.3f}, {h10['ci95'][1]:+.3f}]; p = {h10['wilcoxon_p_one_sided']:.2g}. {v(h10)}.",
     f"- **TabPFN-3.5-Fast vs 3.5** (descriptive): mean precision@k {out['fast_vs_35']['mean_diff_p_at_k']:+.3f}; lower on "
     f"{out['fast_vs_35']['datasets_fast_worse']}/14 datasets; median speed-up {out['fast_vs_35']['median_speedup']:.1f}×.", '',
     '| Dataset | v2 | v3 | 3.5 | 3.5-Fast | 3.5 s/table | Fast s/table |', '|---|---:|---:|---:|---:|---:|---:|']
for r in rows:
    L.append(f"| {r['dataset']} | " + ' | '.join(f"{r['p_at_k'][x]:.2f}" for x in V) + f" | {r['seconds']['V3_5']:.0f} | {r['seconds']['V3_5_FAST']:.0f} |")
L += ['', 'v2.5 and v2.6 were excluded before running (their weights need an interactive license acceptance). Timings are '
      'wall-clock on NVIDIA A10G GPUs, one process per GPU; they include model loading per fit, which affects all versions.']
Path('docs/VERSION_COMPARISON.md').write_text('\n'.join(L) + '\n')
print('\n'.join(L[:12]))
