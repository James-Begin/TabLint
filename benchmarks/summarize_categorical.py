"""Retained benchmark implementation; methodology and scope: docs/BENCHMARKS.md and docs/BENCHMARK_AMENDMENT.md."""
import json, sys
from collections import defaultdict
from pathlib import Path
import numpy as np
from scipy.stats import wilcoxon

D = Path(sys.argv[1] if len(sys.argv) > 1 else 'results/categorical')
BASE = ['frequency', 'logistic', 'rf', 'knn', 'hgb']
by = defaultdict(list)
for p in sorted(D.glob('*_90*.json')):
    r = json.loads(p.read_text()); by[r['dataset']].append(r)
rows, diffs = [], []
for ds, rs in sorted(by.items()):
    pk = {m: float(np.mean([r['precision_at_k'][m] for r in rs])) for m in ['tabpfn'] + BASE}
    au = {m: float(np.mean([r['auroc'][m] for r in rs])) for m in ['tabpfn'] + BASE}
    best = max(BASE, key=pk.get); diffs.append(pk['tabpfn'] - pk[best])
    rows.append({'dataset': ds, 'seeds': len(rs), 'categorical_columns': len(rs[0]['categorical_columns']), 'errors_per_table': rs[0]['errors'],
                 'tabpfn': pk['tabpfn'], 'best_baseline': best, 'best_baseline_p_at_k': pk[best], 'difference': pk['tabpfn'] - pk[best],
                 'tabpfn_auroc': au['tabpfn'], 'best_baseline_auroc': max(au[b] for b in BASE), 'all_p_at_k': pk,
                 'seconds_per_table': float(np.mean([r['seconds'] for r in rs]))})
d = np.array(diffs); rng = np.random.default_rng(0)
b = [rng.choice(d, len(d)).mean() for _ in range(10000)]
h11 = {'wins': int((d > 0).sum()), 'datasets': len(d), 'mean_diff': float(d.mean()), 'ci95': [float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5))],
       'wilcoxon_p_one_sided': float(wilcoxon(d, alternative='greater').pvalue), 'runs': sum(len(v) for v in by.values())}
h11['supported'] = h11['wilcoxon_p_one_sided'] < 0.05
(D / 'summary.json').write_text(json.dumps({'h11': h11, 'per_dataset': rows}, indent=2))
L = ['# Categorical-cell checks: results (H11)', '',
     f"10 public tables × 5 fresh seeds ({h11['runs']} runs), up to 400 rows each (penguins: 344; tips: 244). 3% of categorical cells were swapped to a different "
     'level drawn from the same column (plausible for the column, not a typo). Precision@k vs the per-dataset best of 5 '
     'baselines (frequency, logistic, random forest, kNN, HGB; chosen after the fact). Generated by `benchmarks/summarize_categorical.py`.', '',
     f"**H11 {'supported' if h11['supported'] else 'not supported'}:** TabPFN-3.5 beats the best baseline on **{h11['wins']}/{h11['datasets']}** datasets; "
     f"mean precision@k gain {h11['mean_diff']:+.3f} [{h11['ci95'][0]:+.3f}, {h11['ci95'][1]:+.3f}]; one-sided Wilcoxon p = {h11['wilcoxon_p_one_sided']:.2g}.", '',
     '| Dataset | Categorical columns | Errors per table | TabPFN-3.5 | Best baseline | Baseline precision@k | Δ | TabPFN AUROC | Best baseline AUROC | s/table |',
     '|---|---:|---:|---:|---|---:|---:|---:|---:|---:|']
for r in rows:
    L.append(f"| {r['dataset']} | {r['categorical_columns']} | {r['errors_per_table']} | {r['tabpfn']:.2f} | {r['best_baseline']} | {r['best_baseline_p_at_k']:.2f} | "
             f"{r['difference']:+.2f} | {r['tabpfn_auroc']:.3f} | {r['best_baseline_auroc']:.3f} | {r['seconds_per_table']:.0f} |")
L += ['', 'Notes: a swap to a category that is ordinary for the column and also compatible with the rest of the row is '
      'undetectable by any method, so absolute precision is lower than for numeric cells. Auto MPG was used for a development '
      'smoke test and is excluded. The typo hint ("possible typo of …") is a separate string heuristic and is not part of this test.',
      '', 'The retained 50-run confirmation uses the [frozen original scoring policy](../benchmarks/categorical_reference.py): first-seen category codes and low-cardinality categorical context. The newer product retains high-cardinality categorical inputs with sorted codes; these stored scores do not evaluate that additional context.',
      '', 'Launch-time source fingerprints are stored in `results/categorical/protocol.json`. They identify original run files, '
      'not the current cleaned source. The original protocol draft and launch snapshot are not distributed here; '
      'fresh reproduction uses the current runner and frozen seeds.']
Path('docs/CATEGORICAL_RESULTS.md').write_text('\n'.join(L) + '\n'); print('\n'.join(L[4:]))
