"""Generate docs/RESULTS.md from stored artifacts only (no hand-copied numbers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
conf = json.loads((ROOT / 'results/confirmation/paired_summary.json').read_text())
stab = json.loads((ROOT / 'results/stability_check.json').read_text())['summary']
rec = json.loads((ROOT / 'results/numerical_recovery/results.json').read_text())
det_path = ROOT / 'results/confirmation/detection/summary.json'
det = json.loads(det_path.read_text()) if det_path.exists() else None
prereg = (ROOT / 'docs/CONFIRMATION_PREREG.md').read_text().splitlines()[2].split(',')[0]

L = ['# Results', '', '_Generated by `experiments/make_results.py` from stored JSON artifacts._', '',
     '## 1. Numerical stabilisation of TabPFN-3.5 gradients (model internals)', '',
     'TabPFN 9.1.0 preprocessing (`torch_nanstd`) squares NaN-masked values before masking and '
     'differentiates sqrt at zero variance. Forward values are finite, but backward passes '
     'through outlier clipping / constant columns can produce NaN. `auditkit/stability.py` '
     'replaces only those backward conventions inside a scoped context manager.', '',
     '| Dataset | Probes | Finite gradients (stock) | Finite gradients (stable) | Max abs forward change | Min cosine (both finite) |',
     '|---|---:|---:|---:|---:|---:|']
for ds, s in stab.items():
    cos = 'n/a' if s['min_cosine_when_both_finite'] is None else f"{s['min_cosine_when_both_finite']:.10f}"
    L.append(f"| {ds} | {s['cases']} | {s['finite_without_patch']} | {s['finite_with_patch']} | "
             f"{s['max_forward_delta']:.3g} | {cos} |")
L += ['', 'Fresh context seeds 201–203, 3 targets each, 3 probe types (nearby real rows, perturbed rows, '
      'target duplicates). Original failing development audits replayed with hash-checked contexts:', '',
      '| Artifact | Non-finite entries (stock) | (stable) | Forward change |', '|---|---:|---:|---:|']
for c in rec['cases']:
    L.append(f"| {c['artifact']} | {c['original_nonfinite_gradients']} | {c['patched_nonfinite_gradients']} | "
             f"{c['abs_forward_difference']:.3g} |")
L += ['', '## 2. Pre-registered confirmation benchmark', '', f'Pre-registration: `docs/CONFIRMATION_PREREG.md` ({prereg.strip()})',
      '', 'Primary endpoint: verified decision flip on standard TabPFN-3.5 (fingerprint on, 4 estimators) using the exact '
      'appended rows and labels, k = 3 rows, over all 30 sampled targets per dataset (6 context seeds × 5 targets). '
      'Comparator: better of two query-matched black-box searches. Interval: Bonferroni-adjusted (3 datasets) '
      'two-level bootstrap.', '',
      '| Dataset | Gradient | Random search | Coordinate search | Near rows (init) | Paired diff vs best search | CI | H1 |',
      '|---|---:|---:|---:|---:|---:|---|---|']
for ds, r in conf['by_dataset'].items():
    rt = r['rates']['tabpfn_standard']
    p = r['paired_gradient_minus_best_search']['tabpfn_standard']
    lo, hi = p['ci95']
    L.append(f"| {ds} | {rt['gradient']:.2f} | {rt['random_search']:.2f} | {rt['coordinate_search']:.2f} | "
             f"{rt['near_rows']:.2f} | {p['diff']:+.2f} | [{lo:+.2f}, {hi:+.2f}] ({p['ci_level']:g}%) | "
             f"{'supported' if lo > 0 else 'not supported'} |")
L += ['', '### Secondary: transfer of the same rows to other receivers (gradient vs best search)', '',
      '| Dataset | Receiver | Gradient | Best search | Diff | CI |', '|---|---|---:|---:|---:|---|']
for ds, r in conf['by_dataset'].items():
    for rec_name, p in r['paired_gradient_minus_best_search'].items():
        if rec_name == 'tabpfn_standard':
            continue
        rt = r['rates'][rec_name]
        L.append(f"| {ds} | {rec_name} | {rt['gradient']:.2f} | {rt[p['baseline']]:.2f} | {p['diff']:+.2f} | "
                 f"[{p['ci95'][0]:+.2f}, {p['ci95'][1]:+.2f}] |")

# Benign-label control, computed from confirmation reports.
benign = {}
for f in sorted((ROOT / 'results/confirmation').glob('*.json')):
    r = json.loads(f.read_text())
    if not isinstance(r, dict) or r.get('schema_version') != '1.0':
        continue
    for v in r.get('verification', []):
        if v['model'] == 'tabpfn_standard' and v['attack_method'] == 'gradient' and v.get('candidate_valid') and v.get('flipped'):
            b = benign.setdefault(r['dataset']['dataset'], [0, 0])
            b[0] += 1
            b[1] += int(bool(v.get('benign_label_flip')))
L += ['', '### Control: same rows, benign labels', '',
      'For every verified gradient flip of standard TabPFN, the same appended rows were refit with the '
      "label equal to the model's original prediction.", '',
      '| Dataset | Verified gradient flips | Also flipped with benign labels |', '|---|---:|---:|']
for ds, (n, m) in benign.items():
    L.append(f'| {ds} | {n} | {m} |')


def paired_table(path, title, note, hypothesis=None):
    if not path.exists():
        return
    d = json.loads(path.read_text())
    L.extend(['', title, '', note, '',
              '| Dataset | Gradient | Random search | Coordinate search | Paired diff vs best search | CI | Targets |',
              '|---|---:|---:|---:|---:|---|---:|'])
    for ds, r in d['by_dataset'].items():
        rt = r['rates']['tabpfn_standard']
        p = r['paired_gradient_minus_best_search']['tabpfn_standard']
        L.append(f"| {ds} | {rt['gradient']:.2f} | {rt['random_search']:.2f} | {rt['coordinate_search']:.2f} | "
                 f"{p['diff']:+.2f} | [{p['ci95'][0]:+.2f}, {p['ci95'][1]:+.2f}] ({p.get('ci_level', 95):g}%) | {r['targets']} |")
    if hypothesis:
        verdicts = ', '.join(f"{ds}: {'supported' if r['paired_gradient_minus_best_search']['tabpfn_standard']['ci95'][0] > 0 else 'not supported'}"
                             for ds, r in d['by_dataset'].items())
        L.extend(['', f'{hypothesis} (supported iff the adjusted lower bound > 0): {verdicts}.'])


paired_table(ROOT / 'results/exploratory_steps40/paired_summary.json',
             '### Exploratory (not confirmatory): 40 optimisation steps on development seeds',
             'Development seeds 101–103; motivated confirmation 2. Small n; do not cite as evidence.')
